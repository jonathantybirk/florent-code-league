"""Build representative and stress corpora without changing the legacy corpus.

The representative corpus bootstraps two randomized terrain variants from
each official map. It preserves the official dimensions, Core anchors,
symmetry class, wall count, ore count, initially visible ore count, and
round-one symmetry-candidate counts.

The stress corpus is generated from the broad random generator and adds maps
whose round-one hypotheses agree on the enemy Core anchor while disagreeing
on unseen terrain.
"""

from __future__ import annotations

import argparse
from collections import deque
from dataclasses import dataclass
from pathlib import Path
import random
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))

import generate_maps as gm


ROOT = Path(__file__).resolve().parents[2]
OFFICIAL = ROOT / "maps"
GENERATED = Path(__file__).resolve().parent
VISION_RADIUS_SQ = 36


@dataclass(frozen=True)
class TemplateFeatures:
    name: str
    width: int
    height: int
    cores: tuple[gm.Core, gm.Core]
    symmetries: tuple[gm.Symmetry, ...]
    walls: int
    ores: int
    visible_ores: tuple[int, int]
    ambiguity: tuple[int, int]


def terrain_orbits(
    width: int,
    height: int,
    symmetries: tuple[gm.Symmetry, ...],
) -> list[tuple[tuple[int, int], ...]]:
    """Orbits under the group generated by every requested symmetry."""
    unseen = {(x, y) for y in range(height) for x in range(width)}
    result = []
    while unseen:
        start = min(unseen)
        orbit = {start}
        queue = deque([start])
        while queue:
            tile = queue.popleft()
            for symmetry in symmetries:
                paired = gm.transform(tile, width, height, symmetry)
                if paired not in orbit:
                    orbit.add(paired)
                    queue.append(paired)
        ordered = tuple(sorted(orbit))
        unseen.difference_update(ordered)
        result.append(ordered)
    return result


def visible_from_core(game_map: gm.GameMap, core: gm.Core) -> set[tuple[int, int]]:
    core_tiles = gm.footprint(core.anchor)
    return {
        (x, y)
        for y in range(game_map.height)
        for x in range(game_map.width)
        if min(
            (x - cx) ** 2 + (y - cy) ** 2
            for cx, cy in core_tiles
        )
        <= VISION_RADIUS_SQ
    }


def surviving_round_one(
    game_map: gm.GameMap, team: int
) -> tuple[gm.Symmetry, ...]:
    """Apply only deductions available from that Core's initial observation."""
    cores = {core.team: core for core in game_map.cores}
    own, enemy = cores[team], cores[1 - team]
    visible = visible_from_core(game_map, own)
    survivors = []
    for symmetry in gm.Symmetry:
        candidate = gm.transform_core_anchor(
            own.anchor, game_map.width, game_map.height, symmetry
        )
        if candidate == own.anchor:
            continue
        candidate_foot = gm.footprint(candidate)
        if candidate_foot <= visible and candidate != enemy.anchor:
            continue
        contradicted = False
        for tile in visible:
            paired = gm.transform(
                tile, game_map.width, game_map.height, symmetry
            )
            if (
                paired in visible
                and game_map.rows[tile[1]][tile[0]]
                != game_map.rows[paired[1]][paired[0]]
            ):
                contradicted = True
                break
        if not contradicted:
            survivors.append(symmetry)
    return tuple(survivors)


def features(path: Path) -> TemplateFeatures:
    game_map = gm.read_map(path)
    cores = tuple(sorted(game_map.cores, key=lambda core: core.team))
    visible_ores = []
    ambiguity = []
    for core in cores:
        visible = visible_from_core(game_map, core)
        visible_ores.append(
            sum(game_map.rows[y][x] == gm.ORE for x, y in visible)
        )
        ambiguity.append(len(surviving_round_one(game_map, core.team)))
    return TemplateFeatures(
        path.stem,
        game_map.width,
        game_map.height,
        cores,
        tuple(gm.matching_symmetries(game_map)),
        sum(tile == gm.WALL for row in game_map.rows for tile in row),
        sum(tile == gm.ORE for row in game_map.rows for tile in row),
        tuple(visible_ores),
        tuple(ambiguity),
    )


def _weighted_choice(
    rng: random.Random,
    choices: list[tuple[tuple[int, int], ...]],
    weights: list[float],
) -> tuple[tuple[int, int], ...]:
    return rng.choices(choices, weights=weights, k=1)[0]


def _choose_wall_orbits(
    rng: random.Random,
    orbits: list[tuple[tuple[int, int], ...]],
    count: int,
) -> set[tuple[int, int]] | None:
    """Choose an exact symmetric wall count, biased toward organic clusters."""
    remaining = count
    available = list(orbits)
    walls: set[tuple[int, int]] = set()
    while remaining:
        eligible = [orbit for orbit in available if len(orbit) <= remaining]
        if not eligible:
            return None
        weights = []
        for orbit in eligible:
            adjacent = sum(
                (x + dx, y + dy) in walls
                for x, y in orbit
                for dx in (-1, 0, 1)
                for dy in (-1, 0, 1)
                if dx or dy
            )
            # Several independent clusters avoid collapsing every map into one
            # enormous wall while still looking less like white noise.
            weights.append(1.0 + 5.0 * adjacent + (2.5 if not walls else 0.0))
        chosen = _weighted_choice(rng, eligible, weights)
        walls.update(chosen)
        remaining -= len(chosen)
        available.remove(chosen)
    return walls


def _choose_ore_orbits(
    rng: random.Random,
    orbits: list[tuple[tuple[int, int], ...]],
    count: int,
    visible_a: set[tuple[int, int]],
    visible_b: set[tuple[int, int]],
    target_visible: tuple[int, int],
) -> set[tuple[int, int]] | None:
    """Choose exact ore count while steering initial visibility to the target."""
    for _ in range(300):
        remaining = count
        available = list(orbits)
        ores: set[tuple[int, int]] = set()
        seen_a = seen_b = 0
        while remaining:
            eligible = [orbit for orbit in available if len(orbit) <= remaining]
            if not eligible:
                break
            weights = []
            for orbit in eligible:
                add_a = sum(tile in visible_a for tile in orbit)
                add_b = sum(tile in visible_b for tile in orbit)
                next_a, next_b = seen_a + add_a, seen_b + add_b
                before = abs(seen_a - target_visible[0]) + abs(
                    seen_b - target_visible[1]
                )
                after = abs(next_a - target_visible[0]) + abs(
                    next_b - target_visible[1]
                )
                weights.append(12.0 if after < before else 0.35)
            chosen = _weighted_choice(rng, eligible, weights)
            ores.update(chosen)
            seen_a += sum(tile in visible_a for tile in chosen)
            seen_b += sum(tile in visible_b for tile in chosen)
            remaining -= len(chosen)
            available.remove(chosen)
        if (
            remaining == 0
            and (seen_a, seen_b) == target_visible
        ):
            return ores
    return None


def _core_connected(game_map: gm.GameMap) -> bool:
    cores = sorted(game_map.cores, key=lambda core: core.team)
    reached = gm._reachable(
        game_map,
        gm.spawn_ring(cores[0].anchor, game_map.width, game_map.height),
    )
    return bool(
        reached
        & gm.spawn_ring(cores[1].anchor, game_map.width, game_map.height)
    )


def generate_like(
    template: TemplateFeatures,
    rng: random.Random,
    terrain_symmetries: tuple[gm.Symmetry, ...] | None = None,
    require_ambiguity: tuple[int, int] | None = None,
    require_exact_symmetries: tuple[gm.Symmetry, ...] | None = None,
) -> gm.GameMap:
    symmetries = terrain_symmetries or template.symmetries
    metadata = symmetries[0]
    cores = [gm.Core(c.entity_id, c.team, c.x, c.y) for c in template.cores]
    protected = set().union(
        *(
            gm.core_margin(core.anchor, template.width, template.height)
            for core in cores
        )
    )
    all_orbits = terrain_orbits(template.width, template.height, symmetries)
    buildable = [
        orbit
        for orbit in all_orbits
        if not any(tile in protected for tile in orbit)
    ]
    blank = gm.GameMap(
        template.width,
        template.height,
        [
            [gm.EMPTY for _ in range(template.width)]
            for _ in range(template.height)
        ],
        cores,
        metadata,
    )
    visible_a = visible_from_core(blank, cores[0])
    visible_b = visible_from_core(blank, cores[1])

    target_ambiguity = require_ambiguity or template.ambiguity
    for _attempt in range(3000):
        walls = _choose_wall_orbits(rng, buildable, template.walls)
        if walls is None:
            continue
        rows = [
            [gm.EMPTY for _ in range(template.width)]
            for _ in range(template.height)
        ]
        for x, y in walls:
            rows[y][x] = gm.WALL
        game_map = gm.GameMap(
            template.width, template.height, rows, cores, metadata
        )
        if not _core_connected(game_map):
            continue
        reached = gm._reachable(
            game_map,
            gm.spawn_ring(
                cores[0].anchor, template.width, template.height
            ),
        )
        ore_orbits = [
            orbit
            for orbit in buildable
            if not any(tile in walls for tile in orbit)
            and all(tile in reached for tile in orbit)
        ]
        ores = _choose_ore_orbits(
            rng,
            ore_orbits,
            template.ores,
            visible_a,
            visible_b,
            template.visible_ores,
        )
        if ores is None:
            continue
        for x, y in ores:
            rows[y][x] = gm.ORE
        if tuple(
            len(surviving_round_one(game_map, team)) for team in (0, 1)
        ) != target_ambiguity:
            continue
        if require_exact_symmetries is not None and tuple(
            gm.matching_symmetries(game_map)
        ) != require_exact_symmetries:
            continue
        if gm.validate(game_map):
            continue
        return game_map
    raise RuntimeError(
        f"could not generate profile variant for {template.name}"
    )


def _write(
    path: Path, game_map: gm.GameMap, overwrite: bool
) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"{path} exists; pass --overwrite")
    gm.write_map(path, game_map)
    decoded = gm.read_map(path)
    errors = gm.validate(decoded)
    if errors:
        raise ValueError(f"{path}: {'; '.join(errors)}")


def generate_representative(args: argparse.Namespace) -> None:
    output = Path(args.output) / "representative"
    rng = random.Random(args.seed)
    templates = [
        features(path) for path in sorted(OFFICIAL.glob("*.map26"))
    ]
    generated = []
    for template in templates:
        for variant in range(2):
            game_map = generate_like(template, rng)
            path = output / (
                f"representative-{args.seed}-{template.name}-{variant}.map26"
            )
            _write(path, game_map, args.overwrite)
            generated.append(path)
            print(f"{path}: {gm._statistics(game_map)}")
    print(f"generated {len(generated)} representative maps")


def _runestone_template() -> TemplateFeatures:
    return features(OFFICIAL / "runestone.map26")


def generate_adversarial_ambiguity(
    rng: random.Random, index: int
) -> gm.GameMap:
    """Make mirror-x correct while rotation survives round one and is wrong."""
    template = _runestone_template()
    desired = (gm.Symmetry.HORIZONTAL,)
    for _ in range(200):
        game_map = generate_like(
            template,
            rng,
            terrain_symmetries=desired,
            require_ambiguity=(2, 2),
            require_exact_symmetries=desired,
        )
        # Both hypotheses imply the same opposing Core anchor.
        cores = sorted(game_map.cores, key=lambda core: core.team)
        for core in cores:
            rot = gm.transform_core_anchor(
                core.anchor,
                game_map.width,
                game_map.height,
                gm.Symmetry.ROTATIONAL,
            )
            mirror = gm.transform_core_anchor(
                core.anchor,
                game_map.width,
                game_map.height,
                gm.Symmetry.HORIZONTAL,
            )
            if rot != mirror:
                break
        else:
            # Ensure the two transforms really predict different unseen tiles
            # from at least one initially observed source tile.
            for core in cores:
                visible = visible_from_core(game_map, core)
                if any(
                    game_map.rows[
                        gm.transform(
                            tile,
                            game_map.width,
                            game_map.height,
                            gm.Symmetry.ROTATIONAL,
                        )[1]
                    ][
                        gm.transform(
                            tile,
                            game_map.width,
                            game_map.height,
                            gm.Symmetry.ROTATIONAL,
                        )[0]
                    ]
                    != game_map.rows[
                        gm.transform(
                            tile,
                            game_map.width,
                            game_map.height,
                            gm.Symmetry.HORIZONTAL,
                        )[1]
                    ][
                        gm.transform(
                            tile,
                            game_map.width,
                            game_map.height,
                            gm.Symmetry.HORIZONTAL,
                        )[0]
                    ]
                    for tile in visible
                ):
                    return game_map
    raise RuntimeError(f"could not make adversarial ambiguity map {index}")


def generate_stress(args: argparse.Namespace) -> None:
    output = Path(args.output) / "stress"
    rng = random.Random(args.seed)
    generated = []
    for index in range(24):
        game_map = gm.generate_one(rng, index)
        path = output / (
            f"stress-{args.seed}-{index:03d}-{game_map.symmetry.label}-"
            f"{game_map.width}x{game_map.height}.map26"
        )
        _write(path, game_map, args.overwrite)
        generated.append(path)
        print(f"{path}: {gm._statistics(game_map)}")
    ambiguity_rng = random.Random(args.seed ^ 0xA11B1)
    for index in range(4):
        game_map = generate_adversarial_ambiguity(ambiguity_rng, index)
        path = output / (
            f"stress-{args.seed}-ambiguous-anchor-{index}.map26"
        )
        _write(path, game_map, args.overwrite)
        generated.append(path)
        print(f"{path}: {gm._statistics(game_map)} adversarial-ambiguity")
    print(f"generated {len(generated)} stress maps")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "profile", choices=("representative", "stress", "all")
    )
    parser.add_argument("--seed", type=int, default=20260801)
    parser.add_argument("--output", default=str(GENERATED))
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if args.profile in ("representative", "all"):
        generate_representative(args)
    if args.profile in ("stress", "all"):
        generate_stress(args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
